let uiLang = 'zh';
try {
  const l = browser.i18n?.getUILanguage?.() ?? navigator.language;
  uiLang = l?.toLowerCase().startsWith('zh') ? 'zh' : 'en';
} catch {
  uiLang = 'zh';
}

export function t(zh: string): string {
  if (uiLang === 'zh') return zh;
  return EN[zh] ?? zh;
}

export function isChineseUI(): boolean {
  return uiLang === 'zh';
}
